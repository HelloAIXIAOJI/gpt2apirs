#requires -Version 5.1
# 统一构建入口：默认构建带 tls 的 CLI（BoringSSL + wreq）。
#
# 不按这套环境来会踩两个坑：VS 18 + cmake 4.3 的 Visual Studio 生成器找不到 cl；
# 换 Ninja 后 BoringSSL 又会把 cl 当汇编器。原因与实测见 docs/build-verification.md。
#
# 用法：
#   powershell -File tools/build.ps1 -Release
#   powershell -File tools/build.ps1 -CargoArgs build,--workspace,--all-features
#
# 额外参数原样交给 cargo；脚本只往 target/ 写一个工具链文件，不动仓库其他文件。

[CmdletBinding()]
param(
    [switch]$Release,
    [string[]]$CargoArgs = @('build', '-p', 'gpt2apirs-cli', '--features', 'tls')
)

$ErrorActionPreference = 'Stop'

function Find-VcVars {
    # 这台机器上 ProgramFiles(x86) 可能是空的，先兜住再找 vswhere
    $pf86 = ${env:ProgramFiles(x86)}
    $roots = @()
    if ($pf86) {
        $vswhere = Join-Path $pf86 'Microsoft Visual Studio\Installer\vswhere.exe'
        if (Test-Path $vswhere) {
            $roots += & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath 2>$null
        }
    }
    $roots += @(
        'G:\MSVS\Community18',
        'C:\Program Files\Microsoft Visual Studio\2022\Community',
        'C:\Program Files\Microsoft Visual Studio\2022\Professional'
    )
    foreach ($root in $roots) {
        if (-not $root) { continue }
        $candidate = Join-Path $root 'VC\Auxiliary\Build\vcvars64.bat'
        if (Test-Path $candidate) { return $candidate }
    }
    throw '找不到 vcvars64.bat：需要 Visual Studio 的 C++ 生成工具'
}

$vcvars = Find-VcVars
$vsRoot = Split-Path (Split-Path (Split-Path $vcvars))

# 把 vcvars 的环境灌进当前进程：cargo 的 build script 靠它找 cl 与 cmake
foreach ($line in & cmd.exe /c "`"`"$vcvars`" >nul && set`"") {
    if ($line -match '^([^=]+)=(.*)$') { Set-Item -Path "env:$($matches[1])" -Value $matches[2] }
}

$ninjaDir = Join-Path $vsRoot 'Common7\IDE\CommonExtensions\Microsoft\CMake\Ninja'
if (Test-Path (Join-Path $ninjaDir 'ninja.exe')) {
    $env:PATH = "$ninjaDir;$env:PATH"
} elseif (-not (Get-Command ninja -ErrorAction SilentlyContinue)) {
    throw '找不到 ninja：装一个或确认 VS 自带的 Ninja 目录存在'
}

if (-not (Get-Command nasm -ErrorAction SilentlyContinue)) {
    $nasmDir = 'C:\Program Files\NASM'
    if (Test-Path (Join-Path $nasmDir 'nasm.exe')) {
        $env:PATH = "$nasmDir;$env:PATH"
    } else {
        throw '找不到 nasm：BoringSSL 的 x64 汇编需要它'
    }
}

# 生成物只往 target/ 写，且内容不变就不重写 —— cmake 对时间戳敏感，重写会触发全量重编
$toolchain = Join-Path (Split-Path $PSScriptRoot) 'target\bssl-toolchain.cmake'
$content = @'
# Generated by tools/build.ps1 - do not edit (target/ is gitignored).
# Pin Windows/AMD64 so BoringSSL uses NASM, and match the Rust runtime (release CRT).
set(CMAKE_SYSTEM_NAME Windows)
set(CMAKE_SYSTEM_PROCESSOR AMD64)
set(CMAKE_ASM_NASM_COMPILER "C:/Program Files/NASM/nasm.exe")
set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreadedDLL")
'@

New-Item -ItemType Directory -Force -Path (Split-Path $toolchain) | Out-Null
$existing = if (Test-Path $toolchain) { Get-Content -Raw -Path $toolchain } else { '' }
if ($existing -ne $content) {
    Set-Content -Path $toolchain -Value $content -NoNewline -Encoding ascii
}

$env:CMAKE_GENERATOR = 'Ninja'
$env:CMAKE_TOOLCHAIN_FILE = $toolchain

# powershell -File 把 "a,b,c" 整体塞进一个元素，这里拆开
$cargo = @($CargoArgs | ForEach-Object { $_ -split ',' } | Where-Object { $_ -ne '' })
if ($Release -and $cargo -notcontains '--release') { $cargo += '--release' }

Write-Host "cargo $($cargo -join ' ')"
Write-Host "  CMAKE_GENERATOR      = $env:CMAKE_GENERATOR"
Write-Host "  CMAKE_TOOLCHAIN_FILE = $env:CMAKE_TOOLCHAIN_FILE"
& cargo @cargo
exit $LASTEXITCODE
